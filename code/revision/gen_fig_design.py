# gen_fig_design.py -- written 2026-11-02 13:43 CET. Writes fig_design.tex: the 2x2 chunking design as a grid of tiles
# (bars = texts, length proportional to tokens; dots = topic units, one per 250 tokens, the stand-in for topic count;
# tint = regime) and, to the right, small multiples: one mini grid per comparison with the two compared cells filled.
# Replaces an earlier hand-drawn version: no crossing lines, no detached legend. Usage: python3 gen_fig_design.py
W, H, G = 3.7, 2.15, 0.35            # tile width, height, gap (cm)
TOK = 0.0024                          # cm per token: 250 -> 0.6, 750 -> 1.8
cells = {(0, 0): (250, 750), (0, 1): (250, 250), (1, 0): (750, 750), (1, 1): (750, 250)}
regime = {(0, 0): ("polysemic-like", "fpV"), (1, 1): ("multi-factual-like", "fpB"), (0, 1): ("equal ratio: neither", "black"), (1, 0): ("equal ratio: neither", "black")}
L = ["% fig_design.tex -- generated by gen_fig_design.py; do not edit by hand.",
     "\\definecolor{fpV}{HTML}{D55E00}\\definecolor{fpB}{HTML}{0072B2}%",
     "\\begin{tikzpicture}[font=\\small]"]
def cx(c): return c * (W + G)
def cy(r): return -r * (H + G)
for (r, c), (qt, ct) in cells.items():
    x0, y0 = cx(c), cy(r); name, col = regime[r, c]
    tint = f"{col}!9" if col != "black" else "black!4"
    L.append(f"\\fill[{tint}, rounded corners=3pt] ({x0:.2f},{y0:.2f}) rectangle ({x0 + W:.2f},{y0 - H:.2f});")
    L.append(f"\\node[anchor=north west, font=\\small] at ({x0 + 0.12:.2f},{y0 - 0.1:.2f}) {{Q{qt}$|$C{ct}}};")
    for k, (lab, tok) in enumerate((("query", qt), ("passage", ct))):
        yy = y0 - 0.85 - 0.45 * k
        L.append(f"\\node[anchor=east, font=\\footnotesize, black!65] at ({x0 + 1.4:.2f},{yy:.2f}) {{{lab}}};")
        L.append(f"\\fill[black!18, rounded corners=1.5pt] ({x0 + 1.5:.2f},{yy - 0.12:.2f}) rectangle ({x0 + 1.5 + tok * TOK:.2f},{yy + 0.12:.2f});")
        for t in range(tok // 250):
            L.append(f"\\fill[black!80] ({x0 + 1.5 + (t + 0.5) * 250 * TOK:.2f},{yy:.2f}) circle (2.1pt);")
    style = f"font=\\small\\bfseries, {col}" if col != "black" else "font=\\small, black!60"
    L.append(f"\\node[anchor=south west, {style}] at ({x0 + 0.12:.2f},{y0 - H + 0.08:.2f}) {{{name}}};")
L.append(f"\\node[font=\\footnotesize\\itshape, black!70] at ({cx(0) + W / 2:.2f},0.32) {{chunks of 750 tokens}};")
L.append(f"\\node[font=\\footnotesize\\itshape, black!70] at ({cx(1) + W / 2:.2f},0.32) {{chunks of 250 tokens}};")
L.append(f"\\node[font=\\footnotesize\\itshape, black!70, anchor=east, align=right] at (-0.15,{cy(0) - H / 2:.2f}) {{queries of\\\\250 tokens}};")
L.append(f"\\node[font=\\footnotesize\\itshape, black!70, anchor=east, align=right] at (-0.15,{cy(1) - H / 2:.2f}) {{queries of\\\\750 tokens}};")
# small multiples: one mini grid per comparison
comps = [({(0, 0), (1, 1)}, "Mismatched cells: the signature", "\\cref{sec:signature}; \\cref{fig:signature}, top and middle"),
         ({(0, 0), (0, 1)}, "Same query length, two chunkings", "what the arrangement adds, \\cref{sec:adds}"),
         ({(0, 0), (1, 0)}, "Same chunking, two query lengths", "the query side, \\cref{sec:alternatives}"),
         ({(0, 1), (1, 0)}, "Equal length ratio", "length on its own, \\cref{sec:alternatives}; \\cref{fig:signature}, bottom")]
X0, s, g, dy = 2 * W + G + 1.0, 0.27, 0.05, 1.12
L.append(f"\\node[anchor=west, font=\\footnotesize\\itshape, black!70] at ({X0 - 0.05:.2f},0.32) {{pairs compared (same layout as left)}};")
for k, (pair, title, where) in enumerate(comps):
    ytop = -0.05 - k * dy
    for (r, c) in cells:
        x = X0 + c * (s + g); y = ytop - r * (s + g)
        f = ({(0, 0): "fpV", (1, 1): "fpB"}.get((r, c), "black!55")) if (r, c) in pair else "white"
        L.append(f"\\filldraw[fill={f}, draw=black!45, line width=1pt] ({x:.2f},{y:.2f}) rectangle ({x + s:.2f},{y - s:.2f});")
    L.append(f"\\node[anchor=north west, align=left, font=\\footnotesize, inner sep=0pt] at ({X0 + 2 * s + g + 0.22:.2f},{ytop + 0.02:.2f}) {{\\textbf{{{title}}}\\\\{where}}};")
yk = cy(1) - H - 0.38
L.append(f"\\fill[black!18, rounded corners=1.5pt] (0.05,{yk - 0.12:.2f}) rectangle ({0.05 + 250 * TOK:.2f},{yk + 0.12:.2f});")
L.append(f"\\fill[black!80] ({0.05 + 125 * TOK:.2f},{yk:.2f}) circle (2.1pt);")
L.append(f"\\node[anchor=west, font=\\footnotesize, black!70] at ({0.12 + 250 * TOK:.2f},{yk:.2f}) {{a text of 250 tokens: bar length is text length, each dot one topic unit}};")
L.append("\\end{tikzpicture}%")
open("fig_design.tex", "w").write("\n".join(L) + "\n")
print(len(L), "lines")
