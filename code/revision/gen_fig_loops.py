# gen_fig_loops.py -- written 2026-11-02 14:06 CET. Writes fig_loops_pr.tex from ../theory/h2probe.txt (CLEAN=1 run):
# median LT_max(H1) against effective dimension (participation ratio of the bearings), for synthetic scatter in p
# dimensions (curve), real neighbourhoods (Nobel; two models x two mismatched cells) and random bearings at the same
# scores. Replaces the v4 loops figure (share of samples with a loop vs nominal p; graded B- by Alex, 14:03 CET).
import re, math
t = open("../theory/h2probe.txt").read()
syn = [(int(p), float(h)) for p, h in re.findall(r"synthetic, scatter fills p=(\d+)\s+n=\s*\d+\s+H1 max: median ([0-9.]+)", t)]
synpr = [float(x) for x in re.findall(r"participation ratio of the synthetic bearings: median ([0-9.]+)", t)]
cells = re.findall(r"^(\S+) Q(\d+)\|C(\d+) (real|random bearings)\s+n=\s*\d+\s+H1 max: median ([0-9.]+)", t, re.M)
prs = {(m, q): (float(r), float(n)) for m, q, r, n in re.findall(r"^PR (\S+) Q(\d+)\|C\d+: real median ([0-9.]+) \[[^]]*\]\s+random median ([0-9.]+)", t, re.M)}
assert len(syn) == len(synpr) == 6 and len(cells) == 8 and len(prs) == 4, (len(syn), len(synpr), len(cells), len(prs))
X0, X1, W, H, YM = math.log(2), math.log(100), 9.6, 4.6, 0.065
X = lambda v: (math.log(v) - X0) / (X1 - X0) * W
Y = lambda v: v / YM * H
L = ["% fig_loops_pr.tex -- generated by gen_fig_loops.py from ../theory/h2probe.txt; do not edit by hand.",
     "\\definecolor{fpV}{HTML}{D55E00}%", "\\begin{tikzpicture}[font=\\small]"]
L.append(f"\\draw[black!60] (0,0) -- ({W},0); \\draw[black!60] (0,0) -- (0,{H});")
for v in (2, 5, 10, 20, 50, 100):
    L.append(f"\\draw[black!60] ({X(v):.3f},0) -- ({X(v):.3f},-0.08) node[below] {{{v}}};")
for v in (0, 0.02, 0.04, 0.06):
    L.append(f"\\draw[black!60] (0,{Y(v):.3f}) -- (-0.08,{Y(v):.3f}) node[left] {{{v:g}}};")
    if v: L.append(f"\\draw[black!8] (0,{Y(v):.3f}) -- ({W},{Y(v):.3f});")
L.append(f"\\node[below] at ({W / 2},-0.55) {{effective dimension of the bearings (participation ratio, log scale)}};")
L.append(f"\\node[rotate=90] at (-1.15,{H / 2}) {{median $\\LTmax$}};")
pts = [(X(pr), Y(h)) for (p, h), pr in zip(syn, synpr)]
L.append("\\draw[black, line width=0.9pt] " + " -- ".join(f"({x:.3f},{y:.3f})" for x, y in pts) + ";")
for (p, h), (x, y) in zip(syn, pts):
    L.append(f"\\filldraw[fill=white, draw=black, line width=0.8pt] ({x:.3f},{y:.3f}) circle (2.4pt);")
    L.append(f"\\node[font=\\footnotesize, anchor={'south' if p <= 20 else 'north'}] at ({x:.3f},{y + (0.1 if p <= 20 else -0.1):.3f}) {{$p={p}$}};")
for (m, q, _c, kind, h) in cells:
    pr_real, pr_rand = prs[m, q]
    if kind == "real":
        L.append(f"\\fill[fpV] ({X(pr_real):.3f},{Y(float(h)):.3f}) circle (2.6pt);")
    else:
        x, y = X(pr_rand), Y(float(h))
        L.append(f"\\fill[black!55] ({x - 0.07:.3f},{y - 0.07:.3f}) rectangle ({x + 0.07:.3f},{y + 0.07:.3f});")
L.append(f"\\node[fpV, anchor=south west, align=left, font=\\footnotesize] at ({X(25.5):.3f},{Y(0.0405):.3f}) {{real neighbourhoods\\\\(two models, two cells)}};")
L.append(f"\\node[black!65, anchor=west, align=left, font=\\footnotesize] at ({X(52):.3f},{Y(0.0135):.3f}) {{random bearings,\\\\same scores}};")
L.append(f"\\node[anchor=north east, align=left, font=\\footnotesize] at ({X(13):.3f},{Y(0.025):.3f}) {{synthetic scatter filling\\\\$p$ random dimensions}};")
L.append("\\end{tikzpicture}%")
open("fig_loops_pr.tex", "w").write("\n".join(L) + "\n")
print("ok", syn, synpr)
