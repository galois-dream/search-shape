# Polysemic regime (simulation): lower and more spread cosines to the 50 neighbours. On the 2x2 chunking design,
# compare the polysemic-like cell Q250|C750 with the multi-factual-like Q750|C250 on the mean and the standard
# deviation of the 50 cosines and on W1, and the matched cells Q250|C250 vs Q750|C750 on the same three.
# AUROC = P(first cell > second) + 0.5 P(=), with a cluster bootstrap over documents (B=2000, default_rng(0)), as in
# nobel/src/stats.py. Step 1 (stdlib, local): python3 signature.py extract  -> sig_input.csv.gz (needed columns only)
# Step 2 (numpy): python signature.py stats  -> sig_auroc.csv and sig_summary.txt
# Step 3 (stdlib): python3 signature.py figure -> ../fig_signature.tex (replaced the count table, 2026-11-02 13:21 CET)
