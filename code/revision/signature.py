import numpy as np, pandas as pd
def auc(x, y, wx, wy):
    u, inv = np.unique(np.concatenate([x, y]), return_inverse=True); ix, iy = inv[:len(x)], inv[len(x):]
    out = np.empty(len(wx))
    for r in range(len(wx)):
        sa = np.bincount(ix, weights=wx[r], minlength=len(u)); sb = np.bincount(iy, weights=wy[r], minlength=len(u))
        out[r] = np.sum(sa * (np.cumsum(sb) - sb + 0.5 * sb)) / (sa.sum() * sb.sum())
    return out
df = pd.read_csv(os.path.join(H, "sig_input.csv.gz"), dtype={"doc": str}); rows = []
for (corpus, model), d in df.groupby(["corpus", "model"]):
    docs = sorted(d.doc.unique()); L = {x: i for i, x in enumerate(docs)}
    W = np.vstack([np.ones(len(docs)), np.random.default_rng(0).multinomial(len(docs), np.full(len(docs), 1 / len(docs)), size=2000)])
    for var in VARS:
        for cname, (a, b) in CONTRASTS.items():
            # size-matched: the polysemic-like cell is already C750; only Q750|C250 is subsampled ("dens" rows)
            va = "primary" if var == "dens" else var
            A, Bc = d[(d.variant == va) & (d.cell == a)], d[(d.variant == var) & (d.cell == b)]
            if A.empty or Bc.empty: continue
            for f in FEATS:
                v = auc(A[f].values, Bc[f].values, W[:, A.doc.map(L).values], W[:, Bc.doc.map(L).values])
                lo, hi = np.percentile(v[1:], [2.5, 97.5])
                rows.append(dict(corpus=corpus, model=model, variant=var, contrast=cname, feature=f, auroc=v[0], lo=lo, hi=hi))
R = pd.DataFrame(rows); R.to_csv(os.path.join(H, "sig_auroc.csv"), index=False)
with open(os.path.join(H, "sig_summary.txt"), "w") as fo:
    for (var, c, f), g in R.groupby(["variant", "contrast", "feature"]):
        print(f"{var:8s} {c:10s} {f:7s} n={len(g)} median={g.auroc.median():.2f} range=[{g.auroc.min():.2f},{g.auroc.max():.2f}] "
              f"CI<0.5: {(g.hi < 0.5).sum()}  CI>0.5: {(g.lo > 0.5).sum()}  CI spans 0.5: {((g.lo <= 0.5) & (g.hi >= 0.5)).sum()}", file=fo)
print(open(os.path.join(H, "sig_summary.txt")).read())
