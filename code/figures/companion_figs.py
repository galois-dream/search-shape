# companion_figs.py -- written 2026-11-05 CET. Writes two TikZ figures of the supplement's reader's companion from data:
#   ../supplement/fig_cp_decomp.tex  (a) W1(H0) against the mean nearest-neighbour ratio term, all 878 queries of the
#        Figure 9 cell (Nobel, text-embedding-3-small, Q250|C750); (b) the terms of (5.6)-(5.7) for the Figure 9 query.
#        Source: nobel/out_clean/example_barcode_terms.json (mstpieces.py with DUMPTERMS).
#   ../supplement/fig_cp_gauss.tex   (a) one random Gaussian cloud of 50 points in the plane (seed 0) with its minimum
#        spanning tree, nearest-neighbour edges blue and bridges vermillion; (b) median share of nearest-neighbour bars by
#        dimension (supplement Table SM7, from data/reference_outputs/simods/random_nn_share.txt) against the real 76%.
# Run with any Python that has numpy and scipy: python companion_figs.py   (prints the numbers it draws)
import json, os
import numpy as np
from scipy.sparse.csgraph import minimum_spanning_tree
from scipy.spatial.distance import pdist, squareform
from scipy.stats import spearmanr
H = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(H, "..", "supplement")

# ---- decomposition
d = json.load(open(os.path.join(H, "../../nobel/out_clean/example_barcode_terms.json")))
W, R = np.array(d["cell_W1"]), np.array(d["cell_ratios"]); rs = spearmanr(W, R)[0]
print(f"decomp: n={len(W)} spearman={rs:.3f}; query {d['query_index']}: W1={d['W1']:.4f} ratios={d['ratios']:.4f} "
      f"clump={d['clump']:+.4f} radial={d['radial']:+.4f} scaling={d['scaling']:+.4f} residual={d['residual']:.1e}")
lo, hi = 0.28, 0.42
pts = " ".join(f"({r:.4f},{w:.4f})" for r, w in zip(R, W))
steps = [("ratios", d["ratios"], "tabB"), ("clump", d["clump"], "tabV"), ("radial", d["radial"], "black!45"), ("scaling", d["scaling"], "black!45")]
N = 50
mr, mb = R * 2 * (N - 1) / N, 2 * W            # per query: mean nearest-neighbour ratio, mean bar (= 2 W1)
bars = json.load(open(os.path.join(H, "../../nobel/out_clean/example_barcode.json")))["bars"]
rr = np.array(d["ratios_r"]); bl = np.array([b[0] for b in bars]); fl = [b[1] for b in bars]
print(f"decomp (a): rank correlation mean bar vs mean ratio {spearmanr(mb, mr)[0]:.3f}; (b): mean bar {bl.mean():.4f}, mean ratio {rr.mean():.4f}")
lo, hi = 0.56, 0.84
pts = " ".join(f"({x:.4f},{y:.4f})" for x, y in zip(mr, mb))
L = [r"% fig_cp_decomp.tex -- generated by figs_didactic/companion_figs.py; do not edit by hand.",
     r"\begin{tikzpicture}[font=\small]",
     r"\begin{axis}[name=sc, width=6.2cm, height=6.2cm, xmin=%.2f, xmax=%.2f, ymin=%.2f, ymax=%.2f, axis lines=left," % (lo, hi, lo, hi),
     r"  xlabel={mean nearest-neighbour ratio}, ylabel={mean bar}, tick label style={font=\footnotesize},",
     r"  xtick={0.6,0.7,0.8}, ytick={0.6,0.7,0.8}]",
     r"  \addplot[black!40, line width=1pt, domain=%.2f:%.2f] {x};" % (lo, hi),
     r"  \addplot[only marks, mark=*, mark size=0.9pt, tabB, fill opacity=0.5, draw opacity=0.5] coordinates {" + pts + "};",
     r"  \addplot[only marks, mark=*, mark size=2.6pt, tabV] coordinates {(%.4f,%.4f)};" % (rr.mean(), bl.mean()),
     r"  \node[anchor=south east, font=\footnotesize, align=right] at (axis cs:%.3f,%.3f) {one dot per query\\ grey line: equality\\ rank correlation %.3f};" % (hi - 0.004, lo + 0.004, spearmanr(mb, mr)[0]),
     r"\end{axis}",
     r"\node[anchor=south west, align=left] at (-0.6,5.6) {(a) 878 queries: a simple statistic and\\ persistence rank them alike};",
     r"\begin{scope}[xshift=7.6cm, yshift=0.2cm]",
     r"  \node[anchor=south west, align=left] at (-0.2,5.4) {(b) one query (vermillion in (a)): its bars and\\ its nearest-neighbour ratios look alike};"]
sc, h = 4.2, 0.045            # cm per unit of length; vertical step per bar
def barcode(vals, cols, y0, title, mean, mlab):
    out = [r"  \node[anchor=south west, font=\footnotesize, align=left] at (-0.2,%.2f) {%s};" % (y0 + 0.08, title)]
    for k, (v, c) in enumerate(zip(vals, cols)):
        out.append(r"  \draw[%s, line width=1.1pt] (0,%.3f) -- (%.3f,%.3f);" % (c, y0 - k * h, sc * v, y0 - k * h))
    yb = y0 - len(vals) * h
    out.append(r"  \draw[black, line width=1pt, densely dotted] (%.3f,%.3f) -- (%.3f,%.3f);" % (sc * mean, y0 + 0.05, sc * mean, yb))
    out.append(r"  \node[anchor=west, font=\footnotesize, fill=white, inner sep=1pt] at (%.3f,%.3f) {%s %.2f};" % (sc * mean + 0.06, y0 - 0.85 * len(vals) * h, mlab, mean))
    return out, yb
o1, yb = barcode(bl, ["tabB" if f else "tabV" for f in fl], 4.3, r"49 $H_0$ bars, longest first; \textcolor{tabB}{blue}: nearest-neighbour\\ edges, \textcolor{tabV}{vermillion}: bridges between clumps", bl.mean(), "mean")
o2, yb2 = barcode(np.sort(rr)[::-1], ["black!55"] * len(rr), yb - 0.75, r"50 nearest-neighbour ratios $r_i$, largest first", rr.mean(), "mean")
L += o1 + o2
L.append(r"  \draw[line width=1pt] (0,%.2f) -- (%.2f,%.2f);" % (yb2 - 0.15, sc * 1.25, yb2 - 0.15))
for v in (0, 0.5, 1.0):
    L.append(r"  \draw[line width=1pt] (%.2f,%.2f) -- (%.2f,%.2f) node[below, font=\footnotesize] {%g};" % (sc * v, yb2 - 0.15, sc * v, yb2 - 0.25, v))
L.append(r"  \node[font=\footnotesize] at (%.2f,%.2f) {bar length, or ratio};" % (sc * 0.62, yb2 - 0.85))
L += [r"\end{scope}", r"\end{tikzpicture}"]
open(os.path.join(OUT, "fig_cp_decomp.tex"), "w").write("\n".join(L) + "\n")

# ---- Gaussian cloud
X = np.random.default_rng(0).standard_normal((50, 2))
D = squareform(pdist(X)); T = minimum_spanning_tree(D).tocoo(); Dn = D.copy(); np.fill_diagonal(Dn, np.inf); nn = Dn.argmin(1)
NN = {tuple(sorted((i, nn[i]))) for i in range(50)}
fl = [tuple(sorted((i, j))) in NN for i, j in zip(T.row, T.col)]
share = np.mean(fl); print(f"gauss: 2-D cloud seed 0, nearest-neighbour bars {sum(fl)} of 49 = {share:.2f}")
s = 1.05
G = [r"% fig_cp_gauss.tex -- generated by figs_didactic/companion_figs.py; do not edit by hand.",
     r"\begin{tikzpicture}[font=\small]",
     r"\begin{scope}", r"  \node[anchor=south west] at (-2.6,3.0) {(a) 50 Gaussian points in the plane};"]
for (i, j), f in zip(zip(T.row, T.col), fl):
    G.append(r"  \draw[%s, line width=%s] (%.3f,%.3f) -- (%.3f,%.3f);" % ("tabB" if f else "tabV", "1.1pt" if f else "1.4pt, densely dashed", s * X[i, 0], s * X[i, 1], s * X[j, 0], s * X[j, 1]))
for p in X:
    G.append(r"  \fill (%.3f,%.3f) circle (1.5pt);" % (s * p[0], s * p[1]))
G.append(r"  \node[font=\footnotesize, align=left, anchor=north west] at (-2.6,-2.55) {%d of 49 bars are nearest-neighbour\\ distances (blue); %d join clumps};" % (sum(fl), 49 - sum(fl)))
G.append(r"\end{scope}")
dims = [(1, 0.67), (2, 0.73), (5, 0.78), (20, 0.86), (100, 0.88), (768, 0.90)]
G += [r"\begin{axis}[at={(4.6cm,-2.4cm)}, width=6.4cm, height=5.6cm, ymin=0.6, ymax=0.95, xmin=0.5, xmax=6.5, axis lines=left,",
      r"  xtick={1,...,6}, xticklabels={1,2,5,20,100,768}, xlabel={dimension of the cloud}, ylabel={share of NN bars},",
      r"  tick label style={font=\footnotesize}]",
      r"  \addplot[tabB, line width=1.3pt, mark=*, mark size=2pt] coordinates {" + " ".join(f"({k + 1},{v})" for k, (_, v) in enumerate(dims)) + "};",
      r"  \addplot[tabV, line width=1.3pt, densely dashed, domain=0.5:6.5] {0.76};",
      r"  \node[tabV, font=\footnotesize, anchor=north east] at (axis cs:6.4,0.725) {real, 0.76};",
      r"\end{axis}", r"\node[anchor=south west] at (4.4,3.0) {(b) more dimensions, fewer bridges};", r"\end{tikzpicture}"]
open(os.path.join(OUT, "fig_cp_gauss.tex"), "w").write("\n".join(G) + "\n")
